"""Merge contributed learner counts into the shipped prior (hooks/prior.ts).

usage: python -I aggregate.py <folder of contribution .json files> [--write]

A contribution is the output of `/budget learn export` (schema budget-router-contribution/1).
Safeguards, so one person cannot steer the prior and small groups are not exposed:
  - a cell (kind x model/effort) is included only if at least MIN_CONTRIBUTORS different files have it;
  - each contributor counts for at most CAP_PER_CONTRIBUTOR turns per cell;
  - cells with fewer than MIN_TURNS turns in total are dropped;
  - files with another schema, impossible numbers (ok > n) or unknown arms are rejected.
The result is a table of pseudo-counts: kind (or '*') -> arm -> {s, f}. The plugin treats each cell as
at most 4 observations, so a person's own record takes over quickly.
"""
import collections
import glob
import json
import os
import sys

SCHEMA = 'budget-router-contribution/1'
MIN_CONTRIBUTORS = 3
CAP_PER_CONTRIBUTOR = 60
MIN_TURNS = 30
FAMILIES = ('haiku', 'sonnet', 'opus')
EFFORTS = ('low', 'medium', 'high', 'xhigh', 'max')


def valid_arm(name):
    parts = name.split('·')
    return len(parts) == 2 and parts[0] in FAMILIES and parts[1] in EFFORTS


def valid_tally(t):
    return isinstance(t, dict) and all(isinstance(t.get(k), (int, float)) for k in ('n', 'ok')) and 0 <= t['ok'] <= t['n'] <= 100000


def load(folder):
    good, bad = [], []
    for f in sorted(glob.glob(os.path.join(folder, '*.json'))):
        try:
            d = json.load(open(f, encoding='utf8'))
            ok = d.get('schema') == SCHEMA and isinstance(d.get('arms'), dict) and isinstance(d.get('kinds'), dict)
            ok = ok and all(valid_arm(a) and valid_tally(t) for a, t in d['arms'].items())
            ok = ok and all(valid_arm(a) and valid_tally(t) for row in d['kinds'].values() for a, t in row.items())
        except (ValueError, AttributeError, OSError):
            ok = False
        (good if ok else bad).append((f, d) if ok else f)
    return good, bad


def merge(contribs):
    cells = collections.defaultdict(lambda: {'who': 0, 'n': 0.0, 'ok': 0.0})

    def add(kind, arm, t):
        n = min(t['n'], CAP_PER_CONTRIBUTOR)
        if t['n'] <= 0:
            return
        c = cells[(kind, arm)]
        c['who'] += 1
        c['n'] += n
        c['ok'] += t['ok'] * n / t['n']

    for _f, d in contribs:
        for arm, t in d['arms'].items():
            add('*', arm, t)
        for kind, row in d['kinds'].items():
            for arm, t in row.items():
                add(kind, arm, t)
    table = {}
    for (kind, arm), c in cells.items():
        if c['who'] >= MIN_CONTRIBUTORS and c['n'] >= MIN_TURNS:
            table.setdefault(kind, {})[arm] = {'s': round(c['ok']), 'f': round(c['n'] - c['ok'])}
    return table


def render(table, contributors):
    lines = [
        '// Pseudo-counts shipped with the plugin, generated by study/aggregate.py from contributions people chose',
        '// to share (see README, "Contribute your counts"). A cell needs at least three contributors to be included.',
        "import type { PriorTable } from './smart'",
        '',
        f'export const PRIOR_INFO = {{ version: 1, contributors: {contributors} }}',
        'export const PRIOR: PriorTable = ' + json.dumps(table, indent=2, ensure_ascii=False) + '',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    folder = sys.argv[1] if len(sys.argv) > 1 else '.'
    good, bad = load(folder)
    table = merge(good)
    print(f'{len(good)} valid contributions, {len(bad)} rejected, {sum(len(r) for r in table.values())} cells kept')
    for f in bad:
        print('  rejected:', os.path.basename(f))
    out = render(table, len(good))
    if '--write' in sys.argv:
        target = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'hooks', 'prior.ts')
        open(target, 'w', encoding='utf8', newline='\n').write(out)
        print('wrote', os.path.normpath(target))
    else:
        print(out)
